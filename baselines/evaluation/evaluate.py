from meltingpot.utils.scenarios import population as population_lib


@contextlib.contextmanager
def build_focal_population(
    ckpt_paths, policy_ids, scale
) -> Iterator[Mapping[str, policy_lib.Policy]]:
  """Builds a population from the specified saved models.

  Args:
    ckpt_paths: path where agent policies are stored
    policy ids: policy ids for each agent

  Yields:
    A mapping from policy id to policy required to build focal population for evaluation.
  """
  with contextlib.ExitStack() as stack:
    yield {
        p_id: stack.enter_context(DownsamplingPolicyWraper(EvalPolicy(ckpt_paths, p_id), scale))
        for p_id in policy_ids
    }


def run_evaluation(args):
  """Runs the evaluation on either substrate or any of the supported scenarios.

  This expects to have params.json file and policies stored under the policy path
  generated by training RLLIB agents.

  Supports generation of videos for both substrate and scenario plays during evalaution.
  """

  ray.init()
  config_file = f'{args.config_dir}/params.json'
  f = open(config_file)
  configs = json.load(f)
  if args.eval_on_scenario:
    scenario = args.scenario
  else:
    scenario = configs['env_config']['substrate']
  scaled = configs['env_config']['scaled']

  if args.create_videos:
    video_dir = args.video_dir
  else:
    video_dir = None

  policies_path = args.policies_dir
  roles = configs['env_config']['roles']
  policy_ids = [f"agent_{i}" for i in range(len(roles))]
  names_by_role = defaultdict(list)
  for i in range(len(policy_ids)):
    names_by_role[roles[i]].append(policy_ids[i])

  # Build population and evaluate
  with build_focal_population(policies_path, policy_ids, scaled) as population:
    results = evaluation.evaluate_population(
        population=population,
        names_by_role=names_by_role,
        scenario=scenario,
        num_episodes=args.num_episodes,
        video_root=video_dir)
  return results, scenario


def run_mixed_evaluation(args):
  """Runs evaluation with a custom background population loaded from a second checkpoint.

  Focal agents occupy the first (total - num_background_agents) player slots.
  Background agents occupy the remaining slots, loaded from background_policies_dir.
  Both populations are evaluated on the substrate directly (no DeepMind bots).

  Each player slot gets a deterministic policy assignment via per-slot roles, so
  focal slots always use focal policies and background slots always use background policies.
  """
  ray.init()

  focal_configs = json.load(open(f'{args.config_dir}/params.json'))
  substrate_name = focal_configs['env_config']['substrate']
  scaled = focal_configs['env_config']['scaled']
  n_total = len(focal_configs['env_config']['roles'])
  n_background = args.num_background_agents
  n_focal = n_total - n_background

  focal_ids   = [f"agent_{i}" for i in range(n_focal)]
  bg_ids      = [f"agent_{i}" for i in range(n_background)]

  with contextlib.ExitStack() as stack:
    focal_pop = stack.enter_context(
        build_focal_population(args.policies_dir, focal_ids, scaled))
    bg_pop = stack.enter_context(
        build_focal_population(args.background_policies_dir, bg_ids, scaled))

    # Build a combined policy dict with unique keys per slot so that
    # Population assigns each slot deterministically (one policy per "role").
    combined_policies = {}
    names_by_slot = {}
    for i, p_id in enumerate(focal_ids):
      slot_key = f"focal_slot_{i}"
      combined_policies[slot_key] = focal_pop[p_id]
      names_by_slot[f"focal_slot_{i}"] = [slot_key]
    for i, p_id in enumerate(bg_ids):
      slot_key = f"background_slot_{i}"
      combined_policies[slot_key] = bg_pop[p_id]
      names_by_slot[f"background_slot_{i}"] = [slot_key]

    # Roles list: one unique role per player slot (forces deterministic assignment)
    slot_roles = [f"focal_slot_{i}" for i in range(n_focal)] + \
                 [f"background_slot_{i}" for i in range(n_background)]

    combined_population = population_lib.Population(
        policies=combined_policies,
        names_by_role=names_by_slot,
        roles=slot_roles)

    results = _run_mixed_episodes(
        population=combined_population,
        substrate_name=substrate_name,
        n_focal=n_focal,
        n_total=n_total,
        num_episodes=args.num_episodes)

  return results, substrate_name


def _run_mixed_episodes(population, substrate_name, n_focal, n_total, num_episodes):
  """Steps through episodes manually, tracking focal and background returns separately."""
  factory = meltingpot.substrate.get_factory(substrate_name)
  roles = factory.default_player_roles()

  data = collections.defaultdict(list)

  with factory.build(roles) as env:
    for ep in range(num_episodes):
      population.reset()
      timestep = env.reset()
      focal_return = np.zeros(n_focal)
      bg_return    = np.zeros(n_total - n_focal)

      population.send_timestep(timestep)
      actions = population.await_action()

      while not timestep.step_type.last():
        timestep = env.step(actions)
        rewards  = np.array(timestep.reward)
        focal_return += rewards[:n_focal]
        bg_return    += rewards[n_focal:]
        population.send_timestep(timestep)
        actions = population.await_action()

      data['focal_player_returns'].append(focal_return.tolist())
      data['focal_per_capita_return'].append(float(np.mean(focal_return)))
      data['background_player_returns'].append(bg_return.tolist())
      data['background_per_capita_return'].append(float(np.mean(bg_return)))
      print(f"  Episode {ep + 1}/{num_episodes} — "
            f"focal per capita: {np.mean(focal_return):.2f}  "
            f"background per capita: {np.mean(bg_return):.2f}")

  return pd.DataFrame(data)


if __name__ == "__main__":

  parser = argparse.ArgumentParser(description="Evaluation Script for Multi-Agent RL in Meltingpot")

  parser.add_argument(
      "--num_episodes",
      type=int,
      default=2,
      help="Number of episodes to run evaluation",
  )
  parser.add_argument(
      "--eval_on_scenario",
      type=bool,
      default=False,
      help="Whether to evaluate on scenario. If this is False, evaluation is done on substrate",
  )
  parser.add_argument(
      "--scenario",
      type=str,
      default=None,
      help="Name of the scenario. This cannot be None when eval_on_scenario is set to True.",
  )
  parser.add_argument(
      "--config_dir",
      type=str,
      help="Directory where your experiment config (params.json) is located",
  )
  parser.add_argument(
      "--policies_dir",
      type=str,
      help="Directory where your trained policies are located",
  )
  parser.add_argument(
      "--create_videos",
      type=bool,
      default=False,
      help="Whether to create evaluation videos",
  )
  parser.add_argument(
      "--video_dir",
      type=str,
      help="Directory where you want to store evaluation videos",
  )
  # --- Custom background population flags ---
  parser.add_argument(
      "--background_policies_dir",
      type=str,
      default=None,
      help="Directory where background population policies are located. "
           "When provided, runs a mixed evaluation with custom background agents "
           "instead of DeepMind bots. Evaluated on substrate directly.",
  )
  parser.add_argument(
      "--background_config_dir",
      type=str,
      default=None,
      help="Directory where background population params.json is located. "
           "Defaults to --config_dir if not set.",
  )
  parser.add_argument(
      "--num_background_agents",
      type=int,
      default=2,
      help="Number of background agents (last N player slots). Default: 2.",
  )

  args = parser.parse_args()
  print("Evaluating with the following arguments: ", args)

  if args.background_policies_dir:
    print("Custom background population provided. Running mixed evaluation on substrate.")
    results, scenario = run_mixed_evaluation(args)
  else:
    if args.eval_on_scenario:
      if args.scenario is None:
        raise Exception("Either set evaluate_on_scenario to False or provide a scenario name from supported scenarios")
      if args.scenario not in SUPPORTED_SCENARIOS:
        raise Exception("Provide a valid scenario name from supported scenarios. Supported scenarios are: ", SUPPORTED_SCENARIOS)
    else:
      print("evaluate_on_scenario=False. Evaluating on substrate found in the config file provided.")
    results, scenario = run_evaluation(args)

  results.to_csv(f'{args.config_dir}/results_evals.csv', index=False)
  print(f"\nResults for {scenario}:")
  with pd.option_context('display.max_rows', None, 'display.max_columns', None):
      print(results)

